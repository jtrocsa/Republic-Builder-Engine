// Generates apps/web/src/content/maps/hallway.tmj and its collision module for the Chronicle
// Institute's Entrance Hall — the room the player walks into before the Main Hall, and the first
// room they control their character in. See
// docs/decision-log/0046-institute-entrance-hall-and-escort-walk.md.
//
// Run with: node scripts/generate-hallway-tmj.js   (or `npm run maps:build`)
//
// Which tile is which piece of furniture comes from
// apps/web/src/content/tilesets/maps/hallway.palette.js. Layering, terrain-block tiling and
// collision come from scripts/lib/map-builder.js. This script owns layout only.
//
// Until Phase 62 this was a 6x10 strip of bare stone with no walls, no collision and no blocks
// module, generated by a script that predated MapBuilder and hand-rolled its own layers. That was
// adequate because the corridor was a five-second cutscene nobody could walk in. It is a real hub
// room now, so it is built the way the other two Institute interiors are.
//
// Target anchors are load-bearing: HALLWAY_TARGETS, HALLWAY_SPAWN and HALLWAY_NPC_BEHAVIOURS in
// apps/web/src/main.js place the Director and the player against the furniture stamped below, and
// the escort walk routes between them through the collision this file emits. A stamp may be
// restyled but not moved without re-checking those three.
//
// ## Size
//
// 20x18 at 48px is 960x864, against a rendered `.institute-map` frame of roughly 970x583 at
// 1366x768.
//
// The **width** is copied from the Archive Room exactly, which is what lets this room reuse the
// existing `.institute-map--archive-room, .institute-map--main-hall { aspect-ratio: 20/12 }` rule
// with no new frame CSS. It also sidesteps updateHubCamera()'s one rough edge — a world *narrower*
// than its frame is pinned flush left rather than centred, because the clamp can never return a
// positive offset — since 960 lands within the same handful of pixels the Archive Room already
// ships with.
//
// The **height** is the deliberate half, and it is the opposite choice from the Main Hall's. That
// room is one row shorter than its frame so its north-wall pennants are never sliced. This room is
// six rows taller than its frame, so the camera pans ~280px north across the escort walk: the
// entrance recedes behind the player and the Main Hall doors rise into view as the Director leads
// them there. The pan is the shot.
//
// ## Layout: four open bands crossing one unbroken spine
//
// Same alternating rhythm as the Main Hall (scripts/generate-institute-hall-tmj.js), rotated for a
// room entered from the south and exited to the north:
//
//   rows  0-1   north wall. The Main Hall doors at DOOR_COLS, pennants, torches.
//   rows  2-3   OPEN door approach. A runner, nothing else.
//   rows  4-5   record storage, wall to wall either side of the spine.
//   rows  6-7   OPEN cross-aisle. Stools drawn up to the north edge of the tables below.
//   rows  8-9   the working middle: the intake bench and the reading table.
//   rows 10-11  OPEN cross-aisle — the greeting floor, where the Director waits.
//   rows 12-13  record storage, wall to wall either side of the spine.
//   rows 14-15  OPEN south aisle — where the player spawns, on a sandstone threshold.
//   rows 16-17  south wall. The entry doors, benches and torches on its inner course.
//
// **The invariant: cols 8-11, rows 2-15 carry no `solid` and no `base` stamp.** A four-tile spine
// runs the full length of the room, four full-width open bands cross it, and each furnished band
// stops a tile short of the spine on both sides. A sealed pocket is not constructible from that
// shape — which is the point, because the property then follows from the layout rather than from
// re-checking it by eye. tests/unit/field-map-coordinates.test.js flood-fills the generated
// collision from the spawn and fails on any open cell it cannot reach.
//
// The spine is also what the escort walks: findRoute() takes the Director from his post at
// (10.0, 10.4) to the doors at (10.0, 2.6) straight up the middle of it.
//
// Everything dressing the open bands is `decor` or `base`, so they read as furnished without
// narrowing: rugs lie flat where the player walks on them, stools sit against a table edge where
// they read as drawn up to it, greenery blocks only the bottom 0.6 of its base row and lifts the
// rest to the overlay layer so the player passes behind the foliage. The four greenery stamps
// flanking the spine are the reason this map has an overlay layer at all.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import palette from "../apps/web/src/content/tilesets/maps/hallway.palette.js";
import { MapBuilder } from "./lib/map-builder.js";
import { resolvePalette } from "./lib/palette-gids.js";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MAP_OUT = path.join(REPO_ROOT, "apps/web/src/content/maps/hallway.tmj");
const BLOCKS_OUT = path.join(REPO_ROOT, "apps/web/src/content/maps/hallway.blocks.js");

const WIDTH = 20;
const HEIGHT = 18;

// The wall bands. North and south are two rows so a door leaf (2 tiles tall) sits inside the wall
// rather than hanging into the room; east and west are one column, which is all a wall seen
// edge-on needs.
const WALL_NORTH = 2; // rows 0-1
const WALL_SOUTH = 2; // rows 16-17
const SOUTH = HEIGHT - WALL_SOUTH; // row 16, the south wall's inner course
const INTERIOR = { col1: 1, col2: WIDTH - 2, row1: WALL_NORTH, row2: HEIGHT - WALL_SOUTH - 1 };
// Both doorways on the same two columns, so the room has one straight spine: in from the entrance
// at the south, out to the Main Hall at the north.
const DOOR_COLS = [9, 10];
// The four columns no solid or base stamp may touch — see the invariant in the header.
const SPINE = { col1: 8, col2: 11 };

const { tilesets, gid, gidRect } = resolvePalette(palette);
const T = palette.tiles;
const map = new MapBuilder({ width: WIDTH, height: HEIGHT, gid, gidRect, tilesets });

const isWall = (col, row) =>
  row < WALL_NORTH || row >= HEIGHT - WALL_SOUTH || col === 0 || col === WIDTH - 1;

// Three floor zones, so the room reads as having places in it rather than as one grey box: a
// sandstone threshold inside the entry doors, plank flooring the length of the spine, grey
// flagstone through the working bands either side.
const inThreshold = (col, row) => col >= 7 && col <= 12 && row >= 14 && row <= 15;
const inSpine = (col, row) =>
  col >= DOOR_COLS[0] && col <= DOOR_COLS[1] && row >= WALL_NORTH && row < SOUTH;

// --- ground -------------------------------------------------------------------------------------
for (let row = 0; row < HEIGHT; row += 1) {
  for (let col = 0; col < WIDTH; col += 1) {
    let block = T.floorStone;
    if (isWall(col, row)) {
      // Masonry frames the two doorways; panelling everywhere else. The A4 corner/edge blob set is
      // untouched — a full-bleed material paves any wall run correctly without it.
      block =
        col >= DOOR_COLS[0] && col <= DOOR_COLS[1] && (row < WALL_NORTH || row >= SOUTH)
          ? T.wallStone
          : T.wallPanel;
    } else if (inThreshold(col, row)) {
      block = T.floorSandstone;
    } else if (inSpine(col, row)) {
      block = T.floorWood;
    }
    map.groundBlock(col, row, block);
  }
}

// The walls carry no art of their own on the ground layer's structures counterpart, so their
// collision has to be declared. Each rect stops flush with the painted band: the player's foot box
// runs from 0.06 above their anchor to 0.44 below it, so stopping at the wall face reads as
// standing against the wall rather than a tile short of it.
map.block({ x1: 0, y1: 0, x2: WIDTH, y2: WALL_NORTH, kind: "north wall" });
map.block({ x1: 0, y1: SOUTH, x2: WIDTH, y2: HEIGHT, kind: "south wall" });
map.block({ x1: 0, y1: 0, x2: 1, y2: HEIGHT, kind: "west wall" });
map.block({ x1: WIDTH - 1, y1: 0, x2: WIDTH, y2: HEIGHT, kind: "east wall" });

// --- doorways -----------------------------------------------------------------------------------
// Both doors are stamped `decor`: they sit inside a wall band whose rect already blocks them, and a
// second overlapping rect would only make the generated collision module harder to read.
for (const col of DOOR_COLS) {
  // Out to the Main Hall, in the north wall. The escort walk ends at (10.0, 2.6), immediately in
  // front of these leaves; the masonry reveal painted above marks the opening in the panelling.
  map.stamp(col, 0, T.door, "decor", "main hall door");
  // In from the street, in the south wall, on the same spine. The player spawns just inside it.
  map.stamp(col, SOUTH, T.door, "decor", "institute entrance");
}

// --- rows 4-5: record storage, wall to wall either side of the spine ------------------------------
// Three 2x2 units per side fill cols 1-6 and 13-18 exactly, leaving cols 7 and 12 as the shoulders
// of the spine. Shelf fronts alternate so a long wall of storage doesn't read as one tile repeated.
map.stamp(1, 4, T.cabinetA, "solid", "record cabinet");
map.stamp(3, 4, T.recordShelf, "solid", "record shelf");
map.stamp(5, 4, T.pigeonholeUpper, "solid", "pigeonhole rack");
map.stamp(13, 4, T.pigeonholeLower, "solid", "pigeonhole rack");
map.stamp(15, 4, T.recordShelfAlt, "solid", "record shelf");
map.stamp(17, 4, T.cabinetB, "solid", "record cabinet");
// The shoulders, both `base`: they block only the bottom 0.6 of row 5 and lift their foliage to the
// overlay layer, so a player who rounds them walks behind the leaves. Safe as `base` here — unlike
// the Main Hall's wall props — because the cell each one leaves open above it opens straight onto
// the spine rather than into a nook, so nothing is sealed.
map.stamp(7, 4, T.plantTall, "base", "hall greenery");
map.stamp(12, 4, T.plantTall, "base", "hall greenery");

// --- rows 6-7: the open cross-aisle ---------------------------------------------------------------
// No solid stamps in this band, by design. Only the stools drawn up to the north side of the two
// tables below; a stool is only furniture if there is a table in front of it.

// --- rows 8-9: the working middle ------------------------------------------------------------------
// Records are logged in here on their way to the Archive. Both tables sit entirely inside the band
// and stop three columns short of the spine, so cols 7-12 stay open end to end.
map.stamp(3, 8, T.intakeTable, "solid", "intake bench");
map.stamp(13, 8, T.readingTable, "solid", "reading table");
map.stamp(1, 8, T.plantPotted, "base", "corner greenery");
map.stamp(18, 8, T.plantPotted, "base", "corner greenery");

// Stools, all `decor`, each in the row directly above or below one of the two tables' footprints.
for (const [col, row] of [
  [4, 7],
  [6, 7],
  [14, 7],
  [16, 7],
  [4, 10],
  [6, 10],
  [14, 10],
  [16, 10],
]) {
  map.stamp(col, row, (col + row) % 2 === 0 ? T.stool : T.stoolAlt, "decor", "reading stool");
}

// --- rows 10-11: the greeting floor ----------------------------------------------------------------
// Where the Director waits. HALLWAY_TARGETS.director stands at (10.0, 10.4), on the runner, facing
// south down the spine at the doors the player comes through.
map.stamp(DOOR_COLS[0], 10, T.rugRed, "decor", "greeting runner");

// --- rows 12-13: record storage, mirroring rows 4-5 -------------------------------------------------
map.stamp(1, 12, T.sampleShelfA, "solid", "preserved sample shelf");
map.stamp(3, 12, T.chestA, "solid", "sealed record chest");
map.stamp(5, 12, T.cabinetC, "solid", "record cabinet");
map.stamp(13, 12, T.sampleShelfB, "solid", "preserved sample shelf");
map.stamp(15, 12, T.chestB, "solid", "sealed record chest");
map.stamp(17, 12, T.cabinetD, "solid", "record cabinet");
map.stamp(7, 12, T.plantPotted, "base", "hall greenery");
map.stamp(12, 12, T.plantPotted, "base", "hall greenery");

// --- rows 2-3 and 14-15: the two open approaches ----------------------------------------------------
// Runners laid up both doorways, so the gaps in the stacks read as a route rather than as floor
// nobody furnished.
map.stamp(DOOR_COLS[0], 2, T.rugBlue, "decor", "main hall runner");
map.stamp(DOOR_COLS[0], 14, T.rugGreen, "decor", "entrance runner");

// --- wall dressing ----------------------------------------------------------------------------------
// All `decor`, and all inside a wall band whose rect already blocks — which is what lets the open
// bands stay open while the room still reads as furnished. Storage and seating line the wall's inner
// course, so the player walks past them rather than through them.
map.stamp(1, SOUTH, T.cabinetC, "decor", "entrance record cabinet");
map.stamp(5, SOUTH, T.lowBench, "decor", "entrance bench");
map.stamp(13, SOUTH, T.lowBench, "decor", "entrance bench");
map.stamp(17, SOUTH, T.sampleShelfC, "decor", "preserved sample shelf");
for (const col of [2, 6, 13, 17])
  map.stamp(col, WALL_NORTH - 1, T.wallTorch, "decor", "wall torch");
for (const col of [3, 8, 11, 16]) map.stamp(col, SOUTH, T.wallTorch, "decor", "wall torch");
// Institute colours flanking the Main Hall doors, gold and navy alternating down the north wall.
map.stamp(4, 0, T.bannerNavy, "decor", "institute pennant");
map.stamp(7, 0, T.bannerGold, "decor", "institute pennant");
map.stamp(12, 0, T.bannerGold, "decor", "institute pennant");
map.stamp(15, 0, T.bannerNavy, "decor", "institute pennant");
// Sconces down the long side walls — the only structures art in cols 0 and 19, and therefore what
// backs those two wall rects for the "every rect has drawn art" check.
for (const row of [5, 11]) {
  map.stamp(0, row, T.wallSconce, "decor", "wall sconce");
  map.stamp(WIDTH - 1, row, T.wallSconce, "decor", "wall sconce");
}

writeFileSync(MAP_OUT, JSON.stringify(map.toTmj()));
writeFileSync(BLOCKS_OUT, map.toBlocksModule("HALLWAY_BLOCKS", "scripts/generate-hallway-tmj.js"));
console.log(`wrote ${path.relative(REPO_ROOT, MAP_OUT)} and its blocks module`);
console.log(
  `  ${map.blocks.length} collision rects, interior ${JSON.stringify(INTERIOR)}, ` +
    `spine cols ${SPINE.col1}-${SPINE.col2}`
);
